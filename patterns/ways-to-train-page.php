<script>
document.addEventListener('DOMContentLoaded', function () {

	const params = new URLSearchParams(window.location.search);

	const selectedProgram = params.get('program');


	const programs = {
        'general-fitness': 'General Fitness',
        'weight-management': 'Weight Management',
        'active-50': 'Active 50+',
        'sports-fitness': 'Sports Fitness',
        'performance-training': 'Performance Training'
    };


	const programName = programs[selectedProgram];


	/*
	 * Direct visit to /ways-to-train/
	 *
	 * Keep the generic hero.
	 */
	if (!programName) {
		return;
	}


	/*
	 * Program has already been selected.
	 *
	 * Hide the generic hero content and make
	 * the selected program the main hero.
	 */

	const genericHero = document.querySelector(
		'.club100-training-options-generic'
	);

	const selectedBox = document.querySelector(
		'.club100-selected-program'
	);

	const selectedName = document.querySelector(
		'.club100-selected-program-name'
	);


	if (genericHero) {

		genericHero.style.display = 'none';

	}


	if (
		selectedBox &&
		selectedName
	) {

		selectedName.textContent = programName;

		selectedBox.hidden = false;

	}


	/*
	 * Carry the selected program and plan
	 * to the next step.
	 */

	document
		.querySelectorAll('.club100-plan-cta')
		.forEach(function (link) {

			const text =
				link.textContent
					.trim()
					.toLowerCase();


			let plan = '';


			if (
				text.includes('self')
			) {

				plan = 'self';

			} else if (
				text.includes('group')
			) {

				plan = 'group';

			} else if (
				text.includes('coach')
			) {

				plan = 'coach';

			}


			/*
			 * Ignore generic CTA such as
			 * "Find My Best Option".
			 */
			if (!plan) {
				return;
			}


			const url =
				new URL(
					'/join/',
					window.location.origin
				);


			url.searchParams.set(
				'program',
				selectedProgram
			);


			url.searchParams.set(
				'plan',
				plan
			);


			link.href =
				url.pathname +
				url.search;

		});

});
</script>